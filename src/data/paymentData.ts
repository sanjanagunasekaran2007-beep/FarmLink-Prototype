import { TransactionItem, PaymentStatus, PaymentTimelineStep } from '@/types';

export const generatePaymentTimeline = (status: PaymentStatus, date: string): PaymentTimelineStep[] => {
  const isOrderCompleted = true;
  const isInitiated = status !== 'Pending';
  const isProcessing = status === 'Processing' || status === 'Completed' || status === 'Failed';
  const isCompleted = status === 'Completed';

  return [
    {
      stage: 'Order completed',
      stageKey: 'order_completed',
      timestamp: `${date}, 10:00 AM`,
      description: 'Produce batch delivered and digital POD signed by buyer.',
      isCompleted: isOrderCompleted,
      isCurrent: status === 'Pending',
    },
    {
      stage: 'Payment initiated',
      stageKey: 'payment_initiated',
      timestamp: isInitiated ? `${date}, 10:30 AM` : undefined,
      description: isInitiated 
        ? 'Escrow release triggered through Mandi Automated Clearing.' 
        : 'Awaiting buyer final signoff to initiate release.',
      isCompleted: isInitiated,
      isCurrent: status === 'Pending',
    },
    {
      stage: 'Payment processing',
      stageKey: 'payment_processing',
      timestamp: isProcessing ? `${date}, 11:15 AM` : undefined,
      description: status === 'Failed' 
        ? 'Processing encountered a demo bank gateway timeout. Reconciliation scheduled.' 
        : isProcessing 
        ? 'Direct bank transfer in transit through State Bank Mandi gateway.' 
        : 'Bank clearing queue pending.',
      isCompleted: isProcessing && status !== 'Failed',
      isCurrent: status === 'Processing' || status === 'Failed',
    },
    {
      stage: 'Payment completed',
      stageKey: 'payment_completed',
      timestamp: isCompleted ? `${date}, 12:45 PM` : undefined,
      description: isCompleted 
        ? 'Payout deposited successfully into linked farmer State Bank account (UTR #SBIN-8849102).' 
        : 'Final credit pending settlement completion.',
      isCompleted: isCompleted,
      isCurrent: status === 'Completed',
    },
  ];
};

