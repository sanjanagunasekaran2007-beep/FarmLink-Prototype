import { OrderDeliveryItem, OrderStatus, TrackingStep } from '@/types';

export const generateTrackingSteps = (status: OrderStatus, orderDate: string, expectedDate: string): TrackingStep[] => {
  const isConfirmedDone = status !== 'Pending';
  const isPreparedDone = status === 'Ready for Pickup' || status === 'In Transit' || status === 'Delivered' || status === 'Completed';
  const isReadyDone = isPreparedDone;
  const isPickedUpDone = status === 'In Transit' || status === 'Delivered' || status === 'Completed';
  const isInTransitDone = isPickedUpDone;
  const isDeliveredDone = status === 'Delivered' || status === 'Completed';
  const isCompletedDone = status === 'Completed';

  return [
    {
      stage: 'Order Confirmed',
      stageKey: 'confirmed',
      date: isConfirmedDone ? orderDate : undefined,
      description: isConfirmedDone 
        ? 'Buyer purchase contract confirmed and escrow deposit verified.' 
        : 'Waiting for buyer contract lock.',
      isCompleted: isConfirmedDone,
      isCurrent: status === 'Confirmed' || status === 'Pending',
    },
    {
      stage: 'Harvest Prepared',
      stageKey: 'prepared',
      date: isPreparedDone ? orderDate : undefined,
      description: isPreparedDone 
        ? 'Farmer graded, weighed, and crated the produce for farmgate collection.' 
        : 'Crate packaging and weighing in progress.',
      isCompleted: isPreparedDone,
      isCurrent: false,
    },
    {
      stage: 'Ready for Pickup',
      stageKey: 'ready_for_pickup',
      date: isReadyDone ? orderDate : undefined,
      description: isReadyDone 
        ? 'Produce lot ready at farm gate. Logistics driver dispatched.' 
        : 'Farmer will mark ready once produce is packed.',
      isCompleted: isReadyDone,
      isCurrent: status === 'Ready for Pickup',
    },
    {
      stage: 'Picked Up',
      stageKey: 'picked_up',
      date: isPickedUpDone ? orderDate : undefined,
      description: isPickedUpDone 
        ? 'Driver loaded crates onto vehicle and verified digital gate pass.' 
        : 'Awaiting vehicle arrival at farm plot.',
      isCompleted: isPickedUpDone,
      isCurrent: false,
    },
    {
      stage: 'In Transit',
      stageKey: 'in_transit',
      date: isInTransitDone ? orderDate : undefined,
      description: isInTransitDone 
        ? 'Produce is on the way to buyer mandi / warehouse.' 
        : 'Transport route scheduled.',
      isCompleted: isInTransitDone,
      isCurrent: status === 'In Transit',
    },
    {
      stage: 'Delivered',
      stageKey: 'delivered',
      date: isDeliveredDone ? expectedDate : undefined,
      description: isDeliveredDone 
        ? 'Produce arrived at destination. Quality verified by buyer.' 
        : 'Expected delivery upon arrival.',
      isCompleted: isDeliveredDone,
      isCurrent: status === 'Delivered',
    },
    {
      stage: 'Completed',
      stageKey: 'completed',
      date: isCompletedDone ? expectedDate : undefined,
      description: isCompletedDone 
        ? 'Digital proof of delivery signed. Full escrow payout released to farmer bank.' 
        : 'Payout released automatically upon buyer acknowledgment.',
      isCompleted: isCompletedDone,
      isCurrent: status === 'Completed',
    },
  ];
};

